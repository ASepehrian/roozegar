/** Same pick for everyone on a given day; changes at local midnight. */
export function couplerOfTheDay(anchorDate: Date): Couplet {
  const dayIndex = Math.floor(anchorDate.getTime() / 86400000);
  const idx = ((dayIndex % COUPLETS.length) + COUPLETS.length) % COUPLETS.length;
  return COUPLETS[idx];
}
