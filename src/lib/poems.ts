/** Deterministic couplet for a Tehran day (`anchor` is the day's UTC noon). */
export function coupletOfDay(anchor: Date): Couplet {
  const dayIndex = Math.floor(anchor.getTime() / 86400000);
  // Odd multiplier so consecutive days land far apart in the list instead of
  // walking through it in order.
  const idx = ((dayIndex * 7) % COUPLETS.length + COUPLETS.length) % COUPLETS.length;
  return COUPLETS[idx];
}
